# Optional self-contained toolchain. If this folder has a tools/ directory
# (Android Studio, SDK, Gradle caches; git-ignored, see README.md), sourcing
# this points every Android tool at it so nothing is written to ~/.android,
# ~/.gradle, ~/Android, etc.:
#   source ./env.sh
# Without tools/, it changes nothing and your own JDK and Android SDK are used.

QR3D_SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export QR3D_SRC

if [ -d "$QR3D_SRC/tools" ]; then
  TOOLS="$QR3D_SRC/tools"

  # Android Studio's bundled JDK (JetBrains Runtime) doubles as the build JDK.
  export JAVA_HOME="$TOOLS/android-studio/jbr"

  export ANDROID_HOME="$TOOLS/android-sdk"
  export ANDROID_SDK_ROOT="$ANDROID_HOME"

  # adb keys, analytics settings, SDK caches (normally ~/.android).
  # ANDROID_USER_HOME is the .android dir itself; AGP's analytics code ignores it
  # and only reads ANDROID_PREFS_ROOT (the dir *containing* .android), so both
  # are set and kept consistent.
  export ANDROID_PREFS_ROOT="$TOOLS/android-user"
  export ANDROID_USER_HOME="$ANDROID_PREFS_ROOT/.android"
  export ANDROID_EMULATOR_HOME="$ANDROID_USER_HOME"
  export ANDROID_AVD_HOME="$ANDROID_USER_HOME/avd"

  # Gradle distributions, dependency cache, daemons (normally ~/.gradle).
  export GRADLE_USER_HOME="$TOOLS/gradle-home"

  # Studio config/system/plugins/log paths (file generated by studio.sh).
  export STUDIO_PROPERTIES="$TOOLS/studio-config/idea.properties"

  export PATH="$JAVA_HOME/bin:$ANDROID_HOME/platform-tools:$ANDROID_HOME/cmdline-tools/latest/bin:$TOOLS/android-studio/bin:$PATH"

  mkdir -p "$ANDROID_HOME" "$ANDROID_USER_HOME" "$GRADLE_USER_HOME" "$TOOLS/studio-config"

  # adb ignores ANDROID_USER_HOME and keeps its keys in $HOME/.android, so the
  # real binary is moved to adb.real and replaced by a wrapper that sets HOME to
  # ANDROID_PREFS_ROOT (keys land in ANDROID_USER_HOME). Studio calls
  # platform-tools/adb directly, so it gets the wrapper too. Re-applied here
  # because SDK updates restore the real binary.
  _adb="$ANDROID_HOME/platform-tools/adb"
  if [ -f "$_adb" ] && ! grep -q QR3D_ADB_WRAPPER "$_adb"; then
    [ -f "$_adb.real" ] || mv -f "$_adb" "$_adb.real"
    cat > "$_adb" <<'EOF'
#!/usr/bin/env bash
# QR3D_ADB_WRAPPER: run adb with a HOME inside the project (keys stay there).
here="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
adb_home="$here/../../android-user"
mkdir -p "$adb_home"
HOME="$(cd "$adb_home" && pwd)" exec "$here/adb.real" "$@"
EOF
    chmod +x "$_adb"
  fi
  unset _adb TOOLS
fi
